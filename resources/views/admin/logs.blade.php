<script>
    // Mobile sidebar toggle (unified)
    const menuToggle = document.getElementById('menuToggle');
    const sidebar = document.getElementById('sidebar');
    if (menuToggle) {
        menuToggle.addEventListener('click', function() {
            sidebar.classList.toggle('mobile-open');
        });
    }
    document.addEventListener('click', function(event) {
        const isMobile = window.innerWidth <= 1024;
        if (isMobile && sidebar.classList.contains('mobile-open')) {
            if (!sidebar.contains(event.target) && !menuToggle.contains(event.target)) {
                sidebar.classList.remove('mobile-open');
            }
        }
    });

    // Active nav highlight
    const currentUrl = window.location.pathname;
    document.querySelectorAll('.nav-item').forEach(item => {
        const href = item.getAttribute('href');
        if (href && currentUrl.includes(href) && href !== '/admin/dashboard') {
            item.classList.add('active');
        } else if (currentUrl === '/admin/dashboard' && href === '/admin/dashboard') {
            item.classList.add('active');
        }
    });

    // Filter functions
    function filterLogs() {
        const searchTerm = document.getElementById('searchLogs').value.toLowerCase();
        const actionFilter = document.getElementById('filterAction').value.toLowerCase();
        
        const rows = document.querySelectorAll('#logsTableBody .log-row');
        rows.forEach(row => {
            const text = row.textContent.toLowerCase();
            const actionCell = row.querySelector('td:nth-child(3) span');
            const action = actionCell ? actionCell.textContent.toLowerCase().trim() : '';
            
            const matchesSearch = text.includes(searchTerm);
            const matchesAction = !actionFilter || action === actionFilter;
            
            row.style.display = (matchesSearch && matchesAction) ? '' : 'none';
        });
    }
    
    function resetFilters() {
        document.getElementById('searchLogs').value = '';
        document.getElementById('filterAction').value = '';
        
        const rows = document.querySelectorAll('#logsTableBody .log-row');
        rows.forEach(row => {
            row.style.display = '';
        });
    }
    
    // Enter key search
    document.getElementById('searchLogs').addEventListener('keypress', function(e) {
        if (e.key === 'Enter') filterLogs();
    });

    // Logout Modal Functions
    function openLogoutModal() {
        document.getElementById('logoutModal').classList.add('active');
        document.body.style.overflow = 'hidden';
    }

    function closeLogoutModal() {
        document.getElementById('logoutModal').classList.remove('active');
        document.body.style.overflow = '';
    }

    // Close modal when clicking outside
    document.getElementById('logoutModal').addEventListener('click', function(e) {
        if (e.target === this) {
            closeLogoutModal();
        }
    });

